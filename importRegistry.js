/* ===============================
   ฟังก์ชันแปลงวันเกิด → ค.ศ.
================================= */
function convertToAD(dateStr) {
  if (!dateStr) return "";

  const parts = dateStr.split("/");
  if (parts.length !== 3) return "";

  let [d, m, y] = parts.map(s => s.trim());

  if (!d || !m || !y) return "";

  d = parseInt(d);
  m = parseInt(m);
  y = parseInt(y);

  if (y > 2400) {
    y = y - 543; // แปลง พ.ศ.
  }

  if (y < 100) {
    y = 2000 + y; // เช่น 53 -> 2053 (กรณี 23/11/53)
  }

  if (!d || !m || !y) return "";

  return `${String(d).padStart(2, "0")}/${String(m).padStart(2, "0")}/${y}`;
}

